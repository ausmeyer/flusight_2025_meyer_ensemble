#!/usr/bin/env python
"""
Generate prospective ARIMA forecasts with plain conformal prediction intervals.

This script:
1. Loads pre-computed residuals from retrospective ARIMA forecasts
2. Trains per-location ARIMA models using all available data
3. Issues prospective forecasts for horizons 1-4 from the last date
4. Uses prior-season residuals for plain conformal intervals

Residuals are loaded from files generated by generate_retro_arima.py.

Usage examples:
  - Auto-detect latest imputed file and output to default folder
      python src/generate_prosp_arima.py --auto-latest

  - Explicit file with residuals directory
      python src/generate_prosp_arima.py \
        --data-file data/imputed_sets/imputed_and_stitched_hosp_2025-09-13.csv \
        --residuals-dir forecasts/retrospective/arima \
        --output forecasts/prospective
"""

import os
import argparse
import warnings
import pickle
from typing import Dict, List, Tuple, Optional

import numpy as np
import pandas as pd
from pmdarima import auto_arima, ARIMA
from scipy import stats

# Utils
import sys
sys.path.append(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'utils'))
from pipeline_utils import find_latest_imputed

warnings.filterwarnings("ignore")


CDC_QUANTILES = np.array([
    0.01, 0.025, 0.05, 0.1, 0.15, 0.2, 0.25, 0.3, 0.35, 0.4, 0.45, 0.5,
    0.55, 0.6, 0.65, 0.7, 0.75, 0.8, 0.85, 0.9, 0.95, 0.975, 0.99
])

# Season definition (inclusive): Nov 1 to May 1
SEASON_START_MONTH = 11  # November
SEASON_START_DAY = 1
SEASON_END_MONTH = 5     # May
SEASON_END_DAY = 1

# Cap on log-space residuals to avoid extreme outliers skewing the distribution
# Set to 1.6 to align with bounded-wide sigma max (0.8 * 1.96 ≈ 1.57)
RESIDUAL_CAP = 1.6

# Minimum residuals for conformal intervals
MIN_RESIDUALS_FOR_CONFORMAL = 4

# Residuals file name pattern
RESIDUALS_FILE_PATTERN = 'arima_residuals_h{horizon}.csv'

# Exogenous feature defaults
DEFAULT_DONOR_TOP_K = 5
DEFAULT_DONOR_MIN_OVERLAP = 30
SEASONAL_PERIOD_WEEKS = 52.1775


